export const GLYPH_W = 5;
export const GLYPH_H = 7;
/** Glyph width plus one column of spacing */
export const CELL_W = GLYPH_W + 1;

/** Lit dot coordinates (col, row) for a string, starting at column 0 */
export function textDots(text: string): [number, number][] {
  const dots: [number, number][] = [];
  text
    .toUpperCase()
    .split('')
    .forEach((char, i) => {
      const glyph = GLYPHS[char];
      if (!glyph) return;
      glyph.forEach((bits, row) => {
        for (let col = 0; col < GLYPH_W; col++) {
          if (bits[col] === '1') dots.push([i * CELL_W + col, row]);
        }
      });
    });
  return dots;
}

export function textWidth(text: string) {
  return text.length * CELL_W - 1;
}
