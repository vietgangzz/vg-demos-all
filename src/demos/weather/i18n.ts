export function tr(lang: Lang) {
  return STRINGS[lang];
}

/** Condition text for an hour of forecast */
export function conditionOf(lang: Lang, kind: EnvKind, h: Hour) {
  const t = STRINGS[lang].env;
  if (kind === 'rain' && h.code >= 80) return lang === 'vi' ? 'Mưa rào' : 'Showers';
  if (kind === 'rain' && h.code <= 57) return lang === 'vi' ? 'Mưa phùn' : 'Drizzle';
  if (kind === 'clear' && h.code === 1) return lang === 'vi' ? 'Ít mây' : 'Mostly clear';
  return t[kind];
}
